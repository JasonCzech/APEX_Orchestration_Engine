import { expect, test } from '@playwright/test'

test('gate keyboard editing preserves prompts, drafts and queue focus', async ({ page }) => {
  await page.goto('/approvals')
  const promptRow = page.getByRole('option').filter({ hasText: 'PI 26.3 workload prompt review' })
  await promptRow.click()
  const gate = page.getByRole('region', { name: 'Review prompts' })
  const editor = gate.getByRole('textbox', { name: 'System prompt', exact: true })
  await expect(editor).toBeVisible()
  const original = await editor.innerText()
  await editor.focus()
  await editor.press('Tab')
  await expect(editor).not.toBeFocused()
  expect(await editor.innerText()).toBe(original)
  await expect(gate.getByRole('button', { name: 'Execute phase', exact: true })).toBeVisible()

  const tabs = gate.getByRole('tablist', { name: 'Prompt review tabs' })
  await tabs.getByRole('tab', { name: 'System prompt' }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(tabs.getByRole('tab', { name: 'Phase prompt' })).toBeFocused()
  await promptRow.focus()
  await page.keyboard.press('m')
  await expect(editor).toBeFocused()

  await editor.fill(`${original}\nRetain this operator instruction.`)
  const otherRow = page.getByRole('option').filter({ hasText: 'ACC add-a-line release approval' })
  await otherRow.click()
  const guard = page.getByRole('dialog', { name: 'Unsaved review edits' })
  await expect(guard).toBeVisible()
  await expect(guard).toHaveCSS('padding', '20px')
  await guard.getByRole('button', { name: 'Continue reviewing' }).click()
  await expect(editor).toContainText('Retain this operator instruction.')
  await otherRow.click()
  await guard.getByRole('button', { name: 'Leave and keep draft' }).click()
  await promptRow.click()
  await expect(editor).toContainText('Retain this operator instruction.')

  await gate.getByRole('button', { name: 'Skip phase', exact: true }).click()
  const skip = page.getByRole('dialog', { name: 'Skip this phase?' })
  await expect(skip).toContainText('later phases that require its output cannot run')
  await expect(skip).toContainText('Your unsaved prompt edits will not be applied')
  await skip.getByRole('button', { name: 'Cancel' }).click()
  await gate.getByRole('button', { name: 'Save edits and re-review' }).click()
  await expect(gate.getByRole('button', { name: 'Execute phase', exact: true })).toBeVisible({ timeout: 20_000 })
  await expect(promptRow).toHaveAttribute('aria-selected', 'true')
  await expect(promptRow).not.toContainText('actioned elsewhere')

  await promptRow.focus()
  await page.keyboard.press('j')
  await expect(page.getByRole('option', { selected: true })).toBeFocused()
  await expect(page.getByRole('status').filter({ hasText: 'open on' })).toHaveCount(1)
})

test('a local output revision remains selected through its new interrupt', async ({ page }) => {
  await page.goto('/approvals')
  const row = page.getByRole('option').filter({ hasText: 'ACC add-a-line release approval' })
  await row.click()
  const gate = page.getByRole('region', { name: 'Review phase results' })
  await gate.getByRole('button', { name: 'Request changes' }).click()
  const instructions = gate.getByRole('textbox', { name: 'Revision instructions' })
  await expect(instructions).toBeFocused()
  await instructions.fill('Recheck the release evidence before acceptance.')
  await gate.getByRole('button', { name: 'Re-run with changes' }).click()
  await expect(gate.getByRole('button', { name: 'Request changes' })).toBeVisible({ timeout: 20_000 })
  await expect(row).toHaveAttribute('aria-selected', 'true')
  await expect(row).not.toContainText('actioned elsewhere')
})
